"""Configuration of the capture daemon.

The configuration is a TOML file in ``~/.posetrak/capture/`` (next to the
registry database). It names the session database, the listening address and
access token of the control API, the capture profile applied to cameras at
arm time, the WLANs the cameras may be on, and the cameras themselves::

    [daemon]
    host = "0.0.0.0"
    port = 8765
    token = "..."                 # generated by `posetrak-capture init-config`
    session_db = "D:/captures/2026-10-17.db"
    # credentials_dir = "..."       # where camera COHN credentials are kept

    [profile]
    name = "mocap-120"
    camera_mode = "gopro-13-4k-120"    # camera_modes id the files are verified against
    [profile.settings]                 # symbolic setting names, mapped per camera type
    resolution = "4K"
    fps = 120
    lens = "linear"

    [[network]]
    name = "location"
    ssid = "posetrak-ap"
    discovery = "dhcp_reservation"

    [[camera]]
    label = "gopro-13_01"             # camera_instances.label; how it is controlled
                                      # comes from the registry (`provision` links it)
"""

from __future__ import annotations

import secrets
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Final

#: Directory holding the daemon's configuration, credentials and logs.
DEFAULT_CONFIG_DIR: Final[Path] = Path.home() / ".posetrak" / "capture"

DEFAULT_PORT: Final[int] = 8765

DISCOVERY_METHODS: Final[tuple[str, ...]] = ("dhcp_reservation", "mdns", "ble_reported")
CAMERA_METHODS: Final[tuple[str, ...]] = ("gopro_cohn", "manual")


class ConfigError(ValueError):
    """The configuration file is missing, malformed or inconsistent."""


@dataclass(frozen=True)
class DaemonConfig:
    host: str = "0.0.0.0"
    port: int = DEFAULT_PORT
    token: str = ""
    session_db: Path | None = None
    #: camera registry; None means the default registry
    registry_db: Path | None = None
    #: where camera COHN credentials are kept; None means the default directory
    credentials_dir: Path | None = None
    #: setup used when a capture is armed without choosing one; None means the only setup
    default_setup: str | None = None
    #: where the recordings of captures are copied to; None means a videos directory beside the session database
    offload_dir: Path | None = None
    #: copy the recordings automatically when a capture has stopped
    auto_offload: bool = False


@dataclass(frozen=True)
class ProfileConfig:
    """Settings pushed to cameras at arm time and read back for verification."""

    name: str = "default"
    camera_mode: str | None = None
    settings: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class NetworkConfig:
    """A WLAN the cameras may be on (location access point, home network)."""

    name: str
    ssid: str
    discovery: str = "dhcp_reservation"
    #: camera label -> fixed IP address, for ``dhcp_reservation`` discovery
    addresses: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class CameraConfig:
    label: str
    #: control method; None takes it from the registry (manual if the camera has no endpoint)
    method: str | None = None
    #: device identity of a COHN camera; None takes it from the registry
    gopro_serial: str | None = None


@dataclass(frozen=True)
class SetupCameraConfig:
    """What a setup says about one camera, over what it says about the camera's model."""

    #: name of the registry capture mode the camera uses; None defers to the model entry
    mode: str | None = None
    #: settings applied on top of the mode's (driver vocabulary), for example an exposure time
    settings: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class SetupConfig:
    """A named choice of capture mode for each camera that may take part in a capture."""

    name: str
    #: camera model ("Hero13" or "GoPro Hero13") -> name of the mode its cameras use
    models: dict[str, str] = field(default_factory=dict)
    #: camera label -> per-camera mode and settings
    cameras: dict[str, SetupCameraConfig] = field(default_factory=dict)


@dataclass(frozen=True)
class CaptureConfig:
    daemon: DaemonConfig = field(default_factory=DaemonConfig)
    profile: ProfileConfig = field(default_factory=ProfileConfig)
    networks: tuple[NetworkConfig, ...] = ()
    cameras: tuple[CameraConfig, ...] = ()
    setups: tuple[SetupConfig, ...] = ()

    def setup(self, name: str) -> SetupConfig:
        for setup in self.setups:
            if setup.name == name:
                return setup
        raise ConfigError(f"unknown setup {name!r} (known: {', '.join(s.name for s in self.setups) or 'none'})")

    def network(self, name: str) -> NetworkConfig:
        for net in self.networks:
            if net.name == name:
                return net
        raise ConfigError(f"unknown network {name!r}")

    def network_for_ssid(self, ssid: str | None) -> NetworkConfig | None:
        """Return the network profile whose SSID is *ssid*, if any."""
        if ssid is None:
            return None
        return next((n for n in self.networks if n.ssid == ssid), None)


def default_config_path() -> Path:
    return DEFAULT_CONFIG_DIR / "config.toml"


def new_token() -> str:
    """Return a fresh URL-safe access token."""
    return secrets.token_urlsafe(24)


def _require(table: dict[str, Any], key: str, where: str) -> Any:
    if key not in table:
        raise ConfigError(f"{where}: missing required key {key!r}")
    return table[key]


def _path(section: dict, key: str) -> Path | None:
    """A path setting; surrounding whitespace is ignored and an empty value means unset."""
    value = str(section.get(key) or "").strip()
    return Path(value) if value else None


def parse_config(data: dict[str, Any]) -> CaptureConfig:
    """Build a validated :class:`CaptureConfig` from parsed TOML.

    Raises
    ------
    ConfigError
        On unknown methods, duplicate names, or missing required keys.
    """
    d = data.get("daemon", {})
    port = int(d.get("port", DEFAULT_PORT))
    if not 0 < port < 65536:
        raise ConfigError(f"daemon.port out of range: {port}")
    daemon = DaemonConfig(
        host=str(d.get("host", "0.0.0.0")),
        port=port,
        token=str(d.get("token", "")),
        session_db=_path(d, "session_db"),
        registry_db=_path(d, "registry_db"),
        credentials_dir=_path(d, "credentials_dir"),
        default_setup=str(d["default_setup"]).strip() if d.get("default_setup") else None,
        offload_dir=_path(d, "offload_dir"),
        auto_offload=bool(d.get("auto_offload", False)),
    )

    p = data.get("profile", {})
    profile = ProfileConfig(
        name=str(p.get("name", "default")),
        camera_mode=p.get("camera_mode"),
        settings=dict(p.get("settings", {})),
    )

    networks = []
    for i, n in enumerate(data.get("network", [])):
        where = f"network[{i}]"
        discovery = str(n.get("discovery", "dhcp_reservation"))
        if discovery not in DISCOVERY_METHODS:
            raise ConfigError(f"{where}: unknown discovery {discovery!r} (expected one of {DISCOVERY_METHODS})")
        networks.append(
            NetworkConfig(
                name=str(_require(n, "name", where)),
                ssid=str(_require(n, "ssid", where)),
                discovery=discovery,
                addresses={str(k): str(v) for k, v in n.get("addresses", {}).items()},
            )
        )
    _check_unique([n.name for n in networks], "network name")
    _check_unique([n.ssid for n in networks], "network ssid")

    cameras = []
    for i, c in enumerate(data.get("camera", [])):
        where = f"camera[{i}]"
        method = c.get("method")
        if method is not None and method not in CAMERA_METHODS:
            raise ConfigError(f"{where}: unknown method {method!r} (expected one of {CAMERA_METHODS})")
        cam = CameraConfig(
            label=str(_require(c, "label", where)),
            method=method,
            gopro_serial=c.get("gopro_serial"),
        )
        cameras.append(cam)
    _check_unique([c.label for c in cameras], "camera label")

    setups = [_parse_setup(str(name), table) for name, table in data.get("setup", {}).items()]
    if daemon.default_setup is not None and daemon.default_setup not in [x.name for x in setups]:
        raise ConfigError(f"daemon.default_setup {daemon.default_setup!r} is not a [setup.*] block")

    return CaptureConfig(daemon, profile, tuple(networks), tuple(cameras), tuple(setups))


def _parse_setup(name: str, table: dict[str, Any]) -> SetupConfig:
    where = f"setup.{name}"
    models = table.get("mode", {})
    if not isinstance(models, dict):
        raise ConfigError(f"{where}.mode must be a table of camera model = mode name")
    cameras = {}
    for label, entry in table.get("camera", {}).items():
        if not isinstance(entry, dict):
            raise ConfigError(f"{where}.camera.{label} must be a table")
        cameras[str(label)] = SetupCameraConfig(
            mode=str(entry["mode"]) if entry.get("mode") else None,
            settings=dict(entry.get("settings", {})),
        )
    return SetupConfig(name, {str(k): str(v) for k, v in models.items()}, cameras)


def _check_unique(values: list[str], what: str) -> None:
    seen: set[str] = set()
    for v in values:
        if v in seen:
            raise ConfigError(f"duplicate {what}: {v!r}")
        seen.add(v)


def load_config(path: Path | None = None) -> CaptureConfig:
    """Load and validate the configuration file.

    Raises
    ------
    ConfigError
        If the file does not exist, is not valid TOML, or fails validation.
    """
    path = path or default_config_path()
    if not path.exists():
        raise ConfigError(f"configuration file not found: {path} (create it with `posetrak-capture init-config`)")
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path}: {exc}") from exc
    return parse_config(data)


def render_default_config(token: str, session_db: Path | None = None) -> str:
    """Return the text of a starter configuration file."""
    db_line = f'session_db = "{session_db.as_posix()}"' if session_db else '# session_db = "D:/captures/session.db"'
    return f"""\
# Configuration of the posetrak capture daemon.
# See python/pipeline/capture/config.py for the full format.

[daemon]
host = "0.0.0.0"
port = {DEFAULT_PORT}
token = "{token}"
{db_line}
# Where the recordings of captures are copied to (default: a videos directory
# beside the session database), and whether that happens by itself when a
# capture has stopped. The operator can also switch it in the web UI.
# offload_dir = "D:/captures/videos"
# auto_offload = true

[profile]
name = "default"
# camera_mode = "<camera_modes id the recorded files are verified against>"
# Applied to every camera at arm time and read back; a camera that does not
# end up with these settings is not ready. Hero13 names: resolution (5.3K, 4K,
# 2.7K, 1080 ...), fps (240, 120, 60 ...), lens (linear, wide, hyperview ...),
# bit_rate (standard, high), performance (max, extended_battery, tripod).
# A numeric key is a raw Open GoPro setting id.
[profile.settings]
# resolution = "4K"
# fps = 120
# lens = "linear"

# One block per WLAN the cameras may be on.
# [[network]]
# name = "location"
# ssid = "posetrak-ap"
# discovery = "dhcp_reservation"
# [network.addresses]
# gopro-13_01 = "192.168.8.101"

# A setup says which capture mode (a name from the camera registry's modes of
# the camera model) each camera uses. Per-model entries cover every camera of a
# model; a [setup.NAME.camera.LABEL] table overrides one camera and may add
# driver settings on top of the mode's. With several setups, the operator picks
# one when arming; default_setup (under [daemon]) names the one preselected.
# [setup.default]
# mode = {{ "GoPro Hero13" = "4K 120 linear" }}
# [setup.default.camera.gopro-13_02]
# mode = "2.7K 120 linear"
# [setup.default.camera.gopro-13_02.settings]
# bit_rate = "high"

# One block per camera taking part in captures. The label is the camera's
# label in the camera registry; the control method and the device it is linked
# to come from the registry (`posetrak-capture provision <label>` links it).
# [[camera]]
# label = "gopro-13_01"
"""
