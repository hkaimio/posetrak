"""Derive the skeleton-neighbour distance limits of a pose model from operator labels.

The windowed choice of keypoint candidates scores a candidate by how close it lies to the picks of the
neighbouring keypoints of the skeleton (docs/roadmap/features/keypoint-candidates/keypoint-candidates-design.md,
section 10.4). The distance a pair of neighbours may plausibly have, in box heights, is a property of the
keypoint layout, not of a person, so it ships with the pose model as a table.

The limit of a pair is 1.15 times the 98th percentile of the 2D distance between the two keypoints (divided by the
height of the person's box) over the labelled camera-frames in which both are visible, pooled over the persons and
cameras of the range. A pair with 50 samples or fewer gets no limit and gives no support. Labels inside the hard
windows and inside the ranges named by ``--exclude`` are left out so the table can be evaluated on them.

The labels are those of the frozen evaluation set (``kp_eval_set.toml``); the table in the repository is derived from
range 1 only and evaluated on range 3::

    python python/tools/gt/derive_neighbour_limits.py --root /path/to/kp_eval_set_v1 --range range1 \\
        --out python/posetrak/detection/soma77_neighbour_limits.py
"""
from __future__ import annotations

import argparse
import os
import sys
import tomllib
from pathlib import Path

import numpy as np

from posetrak.detection.pose_models import SOMA77

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kp_gt  # noqa: E402

# The header of the generated module, written so that this file does not itself carry the tags.
SPDX_HEADER = (
    "# SPDX" + "-FileCopyrightText: 2026 Harri Kaimio",
    "#",
    "# SPDX" + "-License-Identifier: Apache-2.0",
)
MARGIN = 1.15
PERCENTILE = 98.0
MIN_SAMPLES = 50


def neighbour_pairs(parents) -> list[tuple[int, int]]:
    """Index pairs (child, parent) of a keypoint tree."""
    return [(child, parent) for child, parent in enumerate(parents) if parent >= 0]


def pair_distances(root: Path, spec: dict, range_key: str, exclude_windows: list[tuple[float, float]]):
    """``{(a, b): [distance in box heights, ...]}`` over the labelled camera-frames of a range."""
    info = spec["ranges"][range_key]
    pairs = neighbour_pairs(SOMA77.parents)
    out: dict[tuple[int, int], list[float]] = {}
    for subject in info["subjects"]:
        directory = root / info["dir"]
        labels = kp_gt.read_labels(directory / f"labels_subject{subject}.npz",
                                   directory / f"units_subject{subject}.json", info["units"])
        cand = kp_gt.read_candidates(directory / f"candidates_subject{subject}.npz")
        skipped = {int(c) for c in info.get("skip_cameras", {}).get(str(subject), [])}
        visible = labels.visible
        by_key = {}
        for cam, kp, frame, x, y in zip(labels.camera[visible], labels.keypoint[visible], labels.frame[visible],
                                        labels.x[visible], labels.y[visible]):
            if int(cam) in skipped:
                continue
            by_key[(int(cam), int(frame), int(kp))] = (float(x), float(y))
        for (cam, frame, kp), (x, y) in by_key.items():
            for a, b in pairs:
                if kp != a:
                    continue
                other = by_key.get((cam, frame, b))
                if other is None:
                    continue
                height = cand.box_height.get((cam, frame))
                if not height:
                    continue
                t = float(cand.time_of(cam, frame))
                if any(t0 <= t <= t1 for t0, t1 in exclude_windows):
                    continue
                out.setdefault((a, b), []).append(float(np.hypot(x - other[0], y - other[1])) / height)
    return out


def derive(distances) -> dict[tuple[str, str], float]:
    """Limit per pair by name, for the pairs with enough samples."""
    names = SOMA77.keypoint_names
    return {
        (names[a], names[b]): round(MARGIN * float(np.percentile(v, PERCENTILE)), 4)
        for (a, b), v in sorted(distances.items())
        if len(v) > MIN_SAMPLES
    }


def render(limits: dict[tuple[str, str], float], source: str) -> str:
    lines = [
        *SPDX_HEADER,
        "",
        '"""Skeleton-neighbour distance limits of the SOMA-77 keypoints, in box heights.',
        "",
        "Generated by ``python/tools/gt/derive_neighbour_limits.py``; do not edit. The limit of a pair is",
        f"{MARGIN} times the {PERCENTILE:g}th percentile of the 2D distance between the two keypoints, divided by the",
        f"height of the person's box, over the labelled camera-frames in which both are visible ({source}).",
        "A pair missing from the table (too few samples) gives the windowed choice no support.",
        '"""',
        "",
        "SOMA77_NEIGHBOUR_LIMITS: dict[tuple[str, str], float] = {",
    ]
    lines += [f'    ("{a}", "{b}"): {v},' for (a, b), v in limits.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=os.environ.get("POSETRAK_KP_EVAL_ROOT"), help="directory of the frozen evaluation set")
    parser.add_argument("--set", default=str(Path(__file__).with_name("kp_eval_set.toml")), help="the evaluation set description")
    parser.add_argument("--range", dest="range_key", default="range1", help="labelled range to derive from")
    parser.add_argument("--out", default=None, help="write the table as a Python module here (default: print a summary)")
    args = parser.parse_args()
    if not args.root:
        parser.error("--root or POSETRAK_KP_EVAL_ROOT is required")
    spec = tomllib.loads(Path(args.set).read_text(encoding="utf-8"))
    windows = [(w["t0"], w["t1"]) for w in spec.get("hard_windows", [])]
    distances = pair_distances(Path(args.root), spec, args.range_key, windows)
    limits = derive(distances)
    samples = sorted(len(v) for v in distances.values())
    print(f"{len(limits)} of {len(distances)} pairs with more than {MIN_SAMPLES} samples; "
          f"samples per pair {samples[0]}..{samples[-1]}; "
          f"limit {min(limits.values()):.3f}..{max(limits.values()):.3f} box heights, median {np.median(list(limits.values())):.3f}")
    if args.out:
        Path(args.out).write_text(render(limits, f"{spec['evaluation_set']['name']}, {args.range_key}"), encoding="utf-8")
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
